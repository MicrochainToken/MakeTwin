const assert=require('node:assert/strict');
const {primary,readout}=require('../templates/viewer/showcase-state.js');
assert.equal(primary([{name:'reset'},{name:'how_to_use'}],[{clip:'reset'}]),'how_to_use');
assert.equal(primary([{name:'run_cycle'},{name:'how_to_use'}],[],'run_cycle'),'run_cycle');
const manifest={parts:[{id:'piston'},{id:'glow',glow:true}],mechanism:{cycleClip:'run_cycle',cycleDegrees:720},clipCameras:{run_cycle:{motionStartSeconds:2,actionEndSeconds:10}}};
const p={clipName:'run_cycle',time:6,duration:11,speed:.5};
assert.equal(readout(p,manifest).angle,360);assert.equal(readout(p,manifest).components,1);
p.time=0;assert.equal(readout(p,manifest).angle,0);
p.clipName='how_to_use';assert.equal(readout(p,manifest).angle,null);
p.clipName='run_cycle';p.time=NaN;assert.equal(readout(p,manifest).angle,null);
console.log('ok showcase selection and state-derived readouts');
const drawer={metrics:[{label:'Drawer extension',unit:'mm',clip:'drawer',samples:[[0,0],[2,0],[4,120],[5,120],[7,0]]}]};
const d={clipName:'drawer',time:3,duration:7,speed:1};
assert.equal(readout(d,drawer).metric.value,60);
d.time=4.5;assert.equal(readout(d,drawer).metric.value,120);
d.time=6;assert.equal(readout(d,drawer).metric.value,60);
d.time=7;assert.equal(readout(d,drawer).metric.value,0);
d.clipName='other';assert.equal(readout(d,drawer).metric,null);
assert.equal(readout(d,{}).metric,null);
p.clipName='run_cycle';p.time=6;
assert.equal(readout(p,{...manifest,metrics:[]}).metric,null);
assert.equal(readout(p,manifest).metric.label,'Crank angle');
d.clipName='drawer';
